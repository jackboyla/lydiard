import assert from 'node:assert/strict';
import { buildHeartRateDurationProfile } from '../src/analysis/heartRateDuration';
import type { CoachActivitySummary } from '../src/analysis/coachEngine';
const asOf = '2026-09-15T12:00:00Z';
function run(id: string, bpm: number, date = '2026-09-14T00:00:00Z', seconds = 120): CoachActivitySummary {
  return { id, name: id, sportType: 'Run', startDate: date, distanceKm: 1, movingTimeSec: seconds,
    streams: { timeSec: Array.from({ length: seconds + 1 }, (_, i) => i), heartRateBpm: Array(seconds + 1).fill(bpm) } };
}
const spike = run('spike', 170);
spike.maxHeartRate = 250;
spike.streams!.heartRateBpm![60] = 225;
let result = buildHeartRateDurationProfile([spike], asOf);
assert.equal(result.maxObserved?.bpm, 170, 'A summary max and one-second spike must not set observed maximum');
assert.equal(result.rawMaxBpm, 225);
assert.equal(result.excludedSamples, 1);
assert(result.points.every((p) => p.bpm === 170));
assert.equal(result.maxObserved?.confidence, 'single_run');
result = buildHeartRateDurationProfile([run('peak', 190), run('repeat', 188), spike], asOf);
assert.equal(result.maxObserved?.bpm, 190);
assert.equal(result.maxObserved?.confidence, 'repeated');
assert.equal(result.maxObserved?.supportingRuns.length, 2);
const gap = run('gap', 195, undefined, 40);
gap.streams!.timeSec = [0, 5, 10, 40, 45, 50, 55];
gap.streams!.heartRateBpm = Array(7).fill(195);
assert.equal(buildHeartRateDurationProfile([gap], asOf).maxObserved?.bpm, 195, 'Local sample support can be valid despite a gap elsewhere');
assert(!buildHeartRateDurationProfile([gap], asOf).points.some((p) => p.durationSec >= 30), 'A gap must not form a continuous 30-second average');
const variableSampling = run('five-second', 183);
variableSampling.streams = { timeSec: [0, 5, 10, 15, 20, 25, 30], heartRateBpm: Array(7).fill(183) };
assert.equal(buildHeartRateDurationProfile([variableSampling], asOf).maxObserved?.bpm, 183);
const broken = run('broken', 210);
broken.streams!.timeSec![40] = 0;
assert.equal(buildHeartRateDurationProfile([broken], asOf).points.length, 0);
const dates = [run('day30', 180, '2026-08-17T00:00:00Z'), run('day31', 185, '2026-08-16T23:59:59Z'), run('day60', 190, '2026-07-18T00:00:00Z'), run('day90', 195, '2026-06-18T00:00:00Z'), run('day91', 220, '2026-06-17T23:59:59Z'), run('future', 220, '2026-09-15T13:00:00Z')];
result = buildHeartRateDurationProfile(dates, asOf);
for (const [period, expected] of [[30, 180], [60, 190], [90, 195]]) assert.equal(result.points.find((p) => p.periodDays === period)?.bpm, expected);
assert.equal(buildHeartRateDurationProfile([run('same-day', 190, '2026-09-15T18:00:00Z')], '2026-09-15').maxObserved?.bpm, 190);
assert.equal(buildHeartRateDurationProfile([{ ...run('summary', 200), streams: undefined, maxHeartRate: 230 }], asOf).maxObserved, undefined);
const supportedSummary = run('supported-summary', 190);
supportedSummary.maxHeartRate = 194;
supportedSummary.streams!.timeSec!.push(121); // tolerate one unmatched trailing time point
result = buildHeartRateDurationProfile([supportedSummary], asOf);
assert.equal(result.maxObserved?.bpm, 194, 'A full-resolution summary peak is valid when the stream supports it within 5 bpm');
const unsupportedSummary = run('unsupported-summary', 180);
unsupportedSummary.maxHeartRate = 194;
assert.equal(buildHeartRateDurationProfile([unsupportedSummary], asOf).maxObserved?.bpm, 180, 'A summary peak without nearby stream support stays excluded');
assert.equal(buildHeartRateDurationProfile([{ ...run('ride', 220), sportType: 'Ride' }], asOf).points.length, 0);
const oldPeak = run('old-peak', 198, '2026-03-01T12:00:00Z');
assert.equal(buildHeartRateDurationProfile([oldPeak], asOf).maxObserved, undefined);
const historical = buildHeartRateDurationProfile([oldPeak], asOf, 365);
assert.equal(historical.maxObserved?.bpm, 198);
assert.equal(historical.points.length, 0, 'Historical max evidence must not leak into recent curves');
const short = run('single-second-peak', 180, undefined, 4);
short.streams!.heartRateBpm = [180, 188, 192, 188, 180];
result = buildHeartRateDurationProfile([short], asOf);
assert.equal(result.maxObserved?.bpm, 192, 'A true one-sample peak must not be averaged down');
assert.equal(result.maxObserved?.durationSec, 0, 'A sample must not claim a held duration');
assert.equal(result.points[0]?.measurement, 'sample');
assert.equal(result.points[0]?.startSec, result.points[0]?.endSec);
const endpoint = run('endpoint', 180, undefined, 2);
endpoint.streams!.heartRateBpm = [188, 190, 192];
assert.equal(buildHeartRateDurationProfile([endpoint], asOf).maxObserved?.bpm, 192, 'Final raw sample is eligible with two nearby prior readings');
endpoint.streams!.heartRateBpm = [180, 181, 210];
assert.notEqual(buildHeartRateDurationProfile([endpoint], asOf).maxObserved?.bpm, 210, 'Unsupported final spike is excluded');
const sparsePeak = run('sparse', 180);
sparsePeak.streams = { timeSec: [0, 5, 10], heartRateBpm: [189, 193, 190] };
result = buildHeartRateDurationProfile([sparsePeak], asOf);
assert.equal(result.maxObserved?.bpm, 193);
assert.equal(result.points[0]?.measurement, 'sample', 'Five-second recording peak is labelled as a sample');
assert(result.points.some((p) => p.durationSec === 5 && p.measurement === 'rolling'));
sparsePeak.streams.timeSec = [0, 6, 12];
assert.equal(buildHeartRateDurationProfile([sparsePeak], asOf).maxObserved, undefined, 'Distant neighbors do not support peak');
console.log('Heart rate duration smoke checks passed: spikes, summary maxima, repeated evidence, gaps, irregular time and date boundaries.');
